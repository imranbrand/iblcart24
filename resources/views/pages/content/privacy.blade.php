<p>This page explains what information {{ config('shop.name') }} collects and how we use it.</p>

<h5 class="fw-bold mt-4">Information we collect</h5>
<ul>
    <li>Account details: name, email address and password (stored in encrypted form)</li>
    <li>Order details: name, phone number, delivery address and the items you order</li>
    <li>Payment references such as a bKash or Nagad Transaction ID</li>
</ul>

<h5 class="fw-bold mt-4">How we use it</h5>
<ul>
    <li>To process, deliver and support your orders</li>
    <li>To send order confirmation and status emails</li>
    <li>To send you one reminder SMS if you enter your phone number at checkout but do not finish the order</li>
    <li>To prevent fake or abusive orders, we may refuse orders from phone numbers with repeated problems</li>
    <li>To keep the website secure and working</li>
</ul>

<h5 class="fw-bold mt-4">Card payments</h5>
<p>Online card payments are handled by our payment provider. We do not see or store your full card details.</p>

<h5 class="fw-bold mt-4">Sharing</h5>
<p>We share your name, phone number and address only with the courier or delivery partner that delivers your order, and with payment providers when needed to complete a payment. We do not sell your personal information.</p>

<h5 class="fw-bold mt-4">Cookies</h5>
<p>We use cookies to keep you logged in and to remember your shopping cart. We may also use Facebook Pixel and Google Analytics to understand how visitors use the website and to measure our advertising.</p>

<h5 class="fw-bold mt-4">Your choices</h5>
<p class="mb-0">You can update or delete your account from your profile page. For any privacy question, see our <a href="{{ route('pages.contact') }}">Contact page</a>.</p>
